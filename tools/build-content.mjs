#!/usr/bin/env node
/* Masarok content build: splits each paid Academy course into
     - a public shell (free lessons in full, paid lessons as title cards with no steps) → <out>/site/courses/<id>.js
     - a paid bundle (the full paid lessons) for the server's R2 bucket → <out>/content/courses/<id>.json
   Usage:
     node tools/build-content.mjs [--src .] [--out build]           build only, and print the upload commands
     node tools/build-content.mjs --src <content repo> --apply <site> also copy the shells into the site and point
                                                                      each course page (English and Arabic) at its one shell file
   Settings: tools/content.json (which courses are paid, which lessons stay free). */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from "node:fs";
import { join, dirname } from "node:path";
import { createHash } from "node:crypto";
import vm from "node:vm";

const args = process.argv.slice(2), opt = (k, d) => { const i = args.indexOf(k); return i > -1 ? args[i + 1] : d; };
const SRC = opt("--src", "."), OUT = opt("--out", "build"), APPLY = opt("--apply", null);
const CONF = JSON.parse(readFileSync(new URL("./content.json", import.meta.url), "utf8")).courses;

// which course files each course page loads, in order
function pageScripts(html) { return [...html.matchAll(/<script src="\/courses\/([\w-]+\.js)"><\/script>/g)].map((m) => m[1]); }
export function loadCourse(files, dir) {
  const window = {}, ctx = vm.createContext({ window, console });
  files.forEach((f) => vm.runInContext(readFileSync(join(dir, "courses", f), "utf8"), ctx, { filename: f }));
  const C = window.MasarokCourse; if (!C) throw new Error("no course in " + files.join(", "));
  (window.MasarokParts || []).forEach((p) => { if (p.course === C.id) C.lessons = C.lessons.concat(p.lessons); });
  C.lessons.sort((a, b) => (a.order || 0) - (b.order || 0));
  return JSON.parse(JSON.stringify(C)); // plain data only
}
// the only lesson fields a locked lesson shows: its title card. Everything else (steps, words, mock, models…) is paid content.
const CARD = ["id", "order", "icon", "mins", "skill", "group", "t", "d", "cc", "lv"];
export function split(C, conf) {
  const free = conf.free || C.lessons.slice(0, 2).map((l) => l.id);
  const paid = C.lessons.filter((l) => !free.includes(l.id));
  const shell = Object.assign({}, C, {
    lessons: C.lessons.map((l) => {
      if (free.includes(l.id)) return l;
      const s = {}; CARD.forEach((k) => { if (l[k] !== undefined) s[k] = l[k]; });
      return Object.assign(s, { locked: true, steps: [] });
    })
  });
  const body = JSON.stringify(paid), version = createHash("sha256").update(body).digest("hex").slice(0, 12);
  shell.version = version;
  return { shell, bundle: { id: C.id, version, unlock: conf.unlock || ["course:" + C.id, "pass"], lessons: paid } };
}

function main() {
  const pages = readdirSync(join(SRC, "academy"), { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(SRC, "academy", d.name, "index.html")));
  const out = [];
  for (const d of pages) {
    const files = pageScripts(readFileSync(join(SRC, "academy", d.name, "index.html"), "utf8"));
    if (!files.length) continue;
    const C = loadCourse(files, SRC), conf = CONF[C.id];
    if (!conf || !conf.paid) { console.log("· " + C.id + ": free course, left as it is"); continue; }
    const { shell, bundle } = split(C, conf);
    const shellJs = "/* Masarok Academy · " + C.id + " (public part). Generated by tools/build-content.mjs: edit the course source, not this file.\n   Paid lessons load from the Masarok server for students who own the course. */\nwindow.MasarokCourse = " + JSON.stringify(shell) + ";\n";
    for (const [p, txt] of [[join(OUT, "site", "courses", C.id + ".js"), shellJs], [join(OUT, "content", "courses", C.id + ".json"), JSON.stringify(bundle)]]) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, txt); }
    out.push({ id: C.id, page: d.name, files, free: shell.lessons.filter((l) => !l.locked).length, paid: bundle.lessons.length, version: bundle.version, kb: Math.round(JSON.stringify(bundle).length / 1024) });
    if (APPLY) {
      writeFileSync(join(APPLY, "courses", C.id + ".js"), shellJs);
      files.filter((f) => f !== C.id + ".js").forEach((f) => { const p = join(APPLY, "courses", f); if (existsSync(p)) unlinkSync(p); });
      for (const page of [join(APPLY, "academy", d.name, "index.html"), join(APPLY, "ar", "academy", d.name, "index.html")]) {
        if (!existsSync(page)) continue;
        let html = readFileSync(page, "utf8"), first = true;
        html = html.replace(/<script src="\/courses\/[\w-]+\.js"><\/script>\n?/g, () => { if (!first) return ""; first = false; return '<script src="/courses/' + C.id + '.js"></script>\n'; });
        writeFileSync(page, html);
      }
    }
  }
  out.forEach((o) => console.log("✓ " + o.id + ": " + o.free + " free lessons, " + o.paid + " paid lessons (" + o.kb + " KB), version " + o.version));
  if (out.length) {
    console.log("\nUpload the paid bundles (from server/api):");
    out.forEach((o) => console.log("  npx wrangler r2 object put masarok-content/courses/" + o.id + ".json --file ../../" + join(OUT, "content", "courses", o.id + ".json") + " --content-type application/json --remote"));
    console.log(APPLY ? "\nShells copied into " + APPLY + " and course pages updated." : "\nPublic shells are in " + join(OUT, "site", "courses") + " (nothing on the site changed).");
  }
}
if (import.meta.url === "file://" + process.argv[1]) main();
